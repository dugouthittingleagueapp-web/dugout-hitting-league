from playwright.sync_api import sync_playwright, expect
import json, re, os
os.makedirs("work/browser", exist_ok=True)
base='http://127.0.0.1:3200'
teams=['Iron Eagles','Powerhouse Panthers','Diamond Wolves','River City Raptors','Storm Chasers','Midnight Mavericks','Falcon Flyers','Capital Sluggers']
rows=['Date,Start Time,End Time,Location,Group,Home Team,Away Team,Notes']
for day in range(1,13):
 for pair in range(4):
  start,end=('6:00 pm','7:00 pm') if pair<2 else ('7:15 pm','8:15 pm')
  rows.append(f'2027-11-{day:02d},{start},{end},Tunnels {"5/6" if pair%2==0 else "7/8"},11U CSV,{teams[pair*2]},{teams[pair*2+1]},Bring spare balls')
csv='\n'.join(rows)
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 page=b.new_page(viewport={'width':1440,'height':1000})
 page.set_default_timeout(12000)
 errors=[]
 page.on('pageerror',lambda e: errors.append(str(e)))
 page.on('dialog',lambda d:d.accept())
 token=page.request.get(base+'/test-session').json()['token']
 script='''localStorage.setItem('dugout_auth_token', TOKEN); sessionStorage.setItem('dugout_auth_token', TOKEN);localStorage.setItem('userRole','admin');localStorage.setItem('lastActivity',String(Date.now()));localStorage.setItem('dugout_current_season','2027');localStorage.setItem('dugout_app_state',JSON.stringify({view:'admin',currentLeague:null,currentMatchId:null,season:'2027',dashboardTab:'matches'}));'''.replace('TOKEN',json.dumps(token))
 # Initialize this page only; subsequent reloads must use the app's own persisted navigation.
 page.goto(base)
 page.evaluate(script)
 page.reload()
 page.get_by_label('Select League Year',exact=True).select_option('2025')
 expect(page.get_by_text('Managing Season:',exact=False)).to_contain_text('2025')
 page.get_by_role('button',name='Schedule',exact=True).click()
 expect(page.get_by_role('heading',name='Season Schedule · 2027')).to_be_visible()
 imp=page.get_by_role('button',name='+ Import Schedule CSV',exact=True)
 # Reject conflicts inside the CSV before any team/league/game is provisioned.
 imp.click();modal=page.get_by_role('dialog');modal.get_by_role('button',name='Paste CSV Text').click()
 bad_csv='Date,Start Time,End Time,Location,Group,Home Team,Away Team\n2027-11-01,6:00 pm,7:00 pm,Tunnels 5/6,Conflict CSV,A,B\n2027-11-01,6:30 pm,7:30 pm,Tunnels 5/6,Conflict CSV,C,D\n2027-11-01,6:45 pm,7:45 pm,Tunnels 7/8,Conflict CSV,E,A'
 modal.locator('textarea').fill(bad_csv)
 modal.get_by_label('Destination for Conflict CSV').select_option('__new__')
 modal.get_by_label('New league name for Conflict CSV').fill('Blocked Conflicts')
 expect(modal.get_by_text(re.compile('Tunnels 5/6 is already booked'))).to_be_visible()
 expect(modal.get_by_text(re.compile('A already has a game'))).to_be_visible()
 expect(modal.get_by_role('button',name='Import Season Schedule (3 Games)',exact=True)).to_be_disabled()
 assert page.request.get(base+'/api/matches?season=2027').json()==[]
 modal.get_by_role('button',name='Cancel',exact=True).click()
 expect(imp).to_be_enabled();imp.click()
 modal=page.get_by_role('dialog')
 expect(modal.get_by_text('Import into active season: 2027',exact=True)).to_be_visible()
 expect(modal.get_by_text('Schedule Preview',exact=False)).to_have_count(0)
 modal.get_by_role('button',name='Paste CSV Text').click()
 modal.locator('textarea').fill(csv)
 import_button=modal.get_by_role('button',name='Import Season Schedule (48 Games)',exact=True)
 expect(import_button).to_be_disabled()
 modal.get_by_label('Destination for 11U CSV').select_option('__new__')
 modal.get_by_label('New league name for 11U CSV').fill('11U - Tuesdays')
 expect(import_button).to_be_enabled()
 page.screenshot(path='work/browser/import-desktop.png',full_page=True)
 import_button.click()
 expect(modal).not_to_be_visible()
 expect(page.get_by_role('button',name='Edit',exact=True)).to_have_count(48)
 # A new league still shares the physical tunnels with all saved leagues.
 imp.click();modal=page.get_by_role('dialog');modal.get_by_role('button',name='Paste CSV Text').click()
 modal.locator('textarea').fill('Date,Start Time,End Time,Location,Group,Home Team,Away Team\n2027-11-01,18:30,19:30,Tunnels 5/6,Other CSV,New Home,New Away')
 modal.get_by_label('Destination for Other CSV').select_option('__new__')
 modal.get_by_label('New league name for Other CSV').fill('Other League')
 expect(modal.get_by_text(re.compile('Saved game: Iron Eagles vs Powerhouse Panthers'))).to_be_visible()
 expect(modal.get_by_role('button',name='Import Season Schedule (1 Games)',exact=True)).to_be_disabled()
 modal.get_by_role('button',name='Cancel',exact=True).click()
 expect(page.get_by_role('button',name='Edit',exact=True)).to_have_count(48)
 page.get_by_role('button',name='Rename teams',exact=True).click()
 panel=page.locator('#schedule-team-names')
 panel.locator('div').filter(has=page.get_by_text('Iron Eagles',exact=False)).filter(has=page.get_by_role('button',name='Rename',exact=True)).last.get_by_role('button',name='Rename',exact=True).click()
 rename=page.get_by_role('dialog',name='Rename team',exact=True)
 rename.get_by_label('New team name').fill('Golden Eagles')
 rename.get_by_role('button',name='Save name',exact=True).click()
 expect(rename).not_to_be_visible()
 expect(panel.get_by_text('Golden Eagles',exact=False)).to_be_visible()
 page.get_by_role('button',name='Hide teams',exact=True).click()
 page.get_by_role('button',name='Edit',exact=True).first.click()
 edit=page.get_by_role('dialog',name='Edit scheduled game',exact=True)
 expect(edit.get_by_role('textbox',name='Notes',exact=True)).to_have_value('Bring spare balls')
 edit.get_by_role('textbox',name='End time',exact=True).fill('5:00 pm')
 edit.get_by_role('button',name='Save changes',exact=True).click()
 expect(edit.get_by_text('End time must be after start time on the same day.',exact=True)).to_be_visible()
 edit.get_by_role('textbox',name='End time',exact=True).fill('7:10 pm')
 edit.get_by_role('combobox',name='Cage / location',exact=True).select_option('The Dugout: Tunnels 7/8')
 edit.get_by_role('textbox',name='Notes',exact=True).fill('Arrive 10 minutes early')
 edit.get_by_role('button',name='Save changes',exact=True).click()
 expect(edit.get_by_text(re.compile('This change would create a schedule conflict'))).to_be_visible()
 # The other tunnels already have a 6pm game. Retain the free original tunnels.
 edit.get_by_role('combobox',name='Cage / location',exact=True).select_option('The Dugout: Tunnels 5/6')
 edit.get_by_role('button',name='Save changes',exact=True).click()
 expect(edit).not_to_be_visible()
 expect(page.get_by_role('button',name='Edit',exact=True)).to_have_count(48)
 page.get_by_role('button',name='Edit',exact=True).first.click()
 expect(edit.get_by_role('textbox',name='Notes',exact=True)).to_have_value('Arrive 10 minutes early')
 expect(edit.get_by_role('combobox',name='Cage / location',exact=True)).to_have_value('The Dugout: Tunnels 5/6')
 edit.get_by_role('button',name='Cancel',exact=True).click()
 # Retry original CSV after a team rename and a schedule edit: receipt prevents another copy.
 imp.click();modal=page.get_by_role('dialog');modal.get_by_role('button',name='Paste CSV Text').click();modal.locator('textarea').fill(csv)
 modal.get_by_label('Destination for 11U CSV').select_option('11U - Tuesdays')
 expect(modal.get_by_text('Previously Imported',exact=True)).to_have_count(48)
 modal.get_by_role('button',name='Import Season Schedule (48 Games)',exact=True).click()
 expect(modal).not_to_be_visible()
 expect(page.get_by_role('button',name='Edit',exact=True)).to_have_count(48)
 # Removal is tested only against synthetic local games.
 page.get_by_role('button',name='Remove',exact=True).last.click()
 confirm=page.get_by_role('dialog',name='Confirm removal of scheduled game',exact=True)
 confirm.get_by_role('button',name='Cancel',exact=True).click()
 expect(page.get_by_role('button',name='Edit',exact=True)).to_have_count(48)
 page.get_by_role('button',name='Remove',exact=True).last.click()
 page.get_by_role('dialog',name='Confirm removal of scheduled game',exact=True).get_by_role('button',name='Remove game',exact=True).click()
 expect(page.get_by_role('button',name='Edit',exact=True)).to_have_count(47)
 page.get_by_role('button',name='Refresh',exact=True).click()
 expect(page.get_by_role('button',name='Edit',exact=True)).to_have_count(47)
 # Mobile file-picker, mapping, scroll, and edit controls on the same local app/database.
 page.set_viewport_size({'width':390,'height':844})
 imp.click();modal=page.get_by_role('dialog')
 modal.locator('input[type=file]').set_input_files({'name':'schedule.csv','mimeType':'text/csv','buffer':csv.encode()})
 modal.get_by_label('Destination for 11U CSV').select_option('11U - Tuesdays')
 expect(modal.get_by_text('Previously Imported',exact=True)).to_have_count(48)
 expect(modal.get_by_role('button',name='Import Season Schedule (48 Games)',exact=True)).to_be_enabled()
 page.screenshot(path='work/browser/import-mobile.png',full_page=True)
 modal.get_by_role('button',name='Cancel',exact=True).click()
 page.get_by_role('button',name='Edit',exact=True).first.click()
 expect(edit.get_by_role('textbox',name='Notes',exact=True)).to_have_value('Arrive 10 minutes early')
 page.screenshot(path='work/browser/edit-mobile.png',full_page=True)
 edit.get_by_role('button',name='Cancel',exact=True).click()
 # Navigate into the league dashboard and check renamed display via unchanged team IDs.
 page.set_viewport_size({'width':1440,'height':1000})
 page.get_by_role('button',name='← Exit Admin',exact=True).click()
 page.get_by_role('button').filter(has=page.get_by_role('heading',name='11U - Tuesdays',exact=True)).click()
 expect(page.locator('div,span').filter(has_text=re.compile(r'^Golden Eagles$')).last).to_be_visible()
 assert not errors, errors
 print('PASS: full app → real API → disposable PostgreSQL. CSV tunnel/team conflicts and cross-league saved-booking conflicts block Import; conflicting edit is rejected before correction. 48-game import, archive/active isolation, rename, edit/notes/cage save/reopen, safe retry after rename, cancel/remove/refresh, mobile CSV upload and edit, league-dashboard renamed display. Production/Neon were never used.')
 b.close()
